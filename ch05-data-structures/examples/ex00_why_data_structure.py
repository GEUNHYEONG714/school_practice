# 왜 자료구조가 필요한가?
#
# 변수 하나로는 한 개의 값만 담을 수 있다.
# 학생 30명의 점수, 도시 100곳의 기온처럼
# "여러 값"을 한꺼번에 다루려면 자료구조가 필요하다.

# --- 변수만 사용 (한계) ---
score1 = 85
score2 = 92
score3 = 78
score4 = 88
# ...
score30 = 95

# 평균? 변수를 일일이 더해야 한다.
avg = (score1 + score2 + score3 + score4 + score30) / 5
print("변수만 사용:", avg)

print()

# --- 리스트(자료구조) 사용 ---
scores = [85, 92, 78, 88,
          90, 76, 100, 82,
          # ... 30개의 점수
          95]

# 평균? 한 줄로!
avg = sum(scores) / len(scores)
print("리스트 사용:", avg)
