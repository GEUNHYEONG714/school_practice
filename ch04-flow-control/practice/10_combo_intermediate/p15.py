"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 15: 해밍수 찾기

1부터 N 사이에서 해밍수를 모두 출력합니다.
해밍수: 2, 3, 5 이외의 소인수를 갖지 않는 양의 정수
예: 1, 2, 3, 4, 5, 6, 8, 9, 10, 12, 15, 16, 18, 20, 24, 25, ...

힌트: 각 수를 2, 3, 5로 나눌 수 있을 때까지 나눈 후 1이 되면 해밍수입니다.
"""

N = int(input("N을 입력하세요: "))
divisors = [2, 3, 5]

for num in range(1, N + 1):
    cp_num = num
    
    # 약수 대입
    for index_num in divisors:
        
        # 0이 될 때까지 나누기
        while cp_num % index_num == 0:
            cp_num //= index_num
            
    # 1이되면 출력
    if cp_num == 1:
        print(num)

