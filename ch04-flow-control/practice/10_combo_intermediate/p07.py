"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 7: 최소공배수

두 정수를 입력받아 최소공배수(LCM)를 구합니다.
공식: LCM(a, b) = a × b ÷ GCD(a, b)

힌트:
- 먼저 유클리드 호제법으로 최대공약수를 구합니다.
- 그 다음 위 공식을 적용하여 최소공배수를 구합니다.
"""

a = int(input("첫 번째 정수: "))
b = int(input("두 번째 정수: "))

# 아래에 최대공약수와 최소공배수를 구하는 코드를 작성하세요
# 처음 입력한 값 저장
num1 = a
num2 = b

# 플래그 대신 반복 조건으로 최대공약수 계산
while b != 0:
    nam = a % b
    a = b
    b = nam

# 최대공약수 출력
gcd = a
print(f"최대공약수(GCD): {gcd}")

# 최소공배수 계산
lcm = num1 * num2 // gcd

# 최소공배수 출력
print(f"최소공배수(LCM): {lcm}")

