"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 6: 최대공약수 (유클리드 호제법)

두 정수를 입력받아 최대공약수(GCD)를 구합니다.
유클리드 호제법: GCD(a, b) = GCD(b, a % b), b가 0이면 a가 GCD

힌트:
- a를 b로 나눈 나머지를 구합니다.
- b가 0이 될 때까지 반복합니다.
- while 반복문을 사용합니다.
"""

a = int(input("첫 번째 정수: "))
b = int(input("두 번째 정수: "))

# 아래에 유클리드 호제법으로 최대공약수를 구하는 코드를 작성하세요
# 원래 입력값 저장
num1 = a
num2 = b

# 계산 과정 출력
print(f"GCD({num1}, {num2}) 계산 과정:")

# b가 0이 될 때까지 반복
while b != 0:
    # 몫과 나머지 계산
    mok = a // b
    nam = a % b

    # 계산 과정 출력
    print(f"  {a} ÷ {b} = {mok} ... 나머지 {nam}")

    # 다음 계산을 위해 값 변경
    a = b
    b = nam

# 최대공약수 출력
print(f"최대공약수: {a}")

