"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 3: 완전수 찾기

사용자로부터 정수 N을 입력받아 1부터 N 사이의 모든 완전수를 출력합니다.
완전수란 자기 자신을 제외한 약수의 합이 자기 자신과 같은 수입니다.
예: 6 = 1 + 2 + 3, 28 = 1 + 2 + 4 + 7 + 14

힌트:
- 1부터 N까지 각 숫자에 대해 약수의 합을 구합니다.
- 1부터 num//2까지 반복하며 나누어 떨어지는 수를 합산합니다.
"""

n = int(input("N을 입력하세요: "))

# 아래에 1~N 사이 완전수를 찾는 코드를 작성하세요
# 1부터 N까지 반복
for num in range(2, n + 1):
    # 약수의 합과 약수 목록 초기화
    total = 0
    divisor_list = []

    # 자기 자신을 제외한 약수 확인
    for index in range(1, num // 2 + 1):
        # 나누어떨어지면 약수에 추가
        if num % index == 0:
            total += index
            divisor_list.append(index)

    # 약수의 합이 자기 자신과 같으면 완전수
    if total == num:
        print(f"{num} = {' + '.join(map(str, divisor_list))}")

