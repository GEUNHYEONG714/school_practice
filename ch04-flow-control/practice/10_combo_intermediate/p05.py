"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 5: 팩토리얼 합

사용자로부터 정수 N을 입력받아 1! + 2! + 3! + ... + N!을 구합니다.
팩토리얼: N! = 1 × 2 × 3 × ... × N

힌트:
- 바깥 반복문으로 1부터 N까지 순회합니다.
- 각 숫자의 팩토리얼을 구한 후 총합에 더합니다.
- 또는 이전 팩토리얼 값을 활용하면 더 효율적입니다. (N! = (N-1)! × N)
"""

n = int(input("N을 입력하세요: "))

# 아래에 1! + 2! + ... + N! 을 구하는 코드를 작성하세요
# 변수 초기화
factorial = 1
total = 0
result = ""

# 1부터 N까지 반복
for i in range(1, n + 1):
    # 팩토리얼 계산
    factorial *= i

    # 팩토리얼 출력
    print(f"{i}! = {factorial}")

    # 팩토리얼 합 계산
    total += factorial

    # 합 출력에 필요한 항 연결
    if i == 1:
        result = "1!"
    else:
        result += f" + {i}!"

# 최종 결과 출력
print(f"{result} = {total}")

