"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 15: 홀수 합계

1부터 100까지의 숫자 중 홀수만 모두 더한 합계를 구하세요.

힌트: for문과 if문, 누적 변수를 사용합니다.
"""

# 아래에 코드를 작성하세요

total = 0  

# 1부터 100까지 반복
for num in range(1, 101):
    # 홀수인 경우 덧셈
    if num % 2 == 1:
        total += num
        
# 출력
print(f"1부터 100까지 홀수의 합: total")

