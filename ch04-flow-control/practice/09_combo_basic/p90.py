"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 90: 가격 할인 누적

상품 개수 N을 입력받고, N개의 상품 가격을 차례로 입력받습니다.
10000원 이상인 상품만 20% 할인을 적용하고,
10000원 미만 상품은 원래 가격 그대로 합산합니다.

출력 형식: "총액: X원"

힌트: for + range로 N번 반복하며 조건에 따라 할인을 적용합니다.
"""

n = int(input("상품 개수: "))
# 아래에 코드를 작성하세요
total = 0

# 입력받은 개수만큼 반복
for _ in range(n):

    # 상품 가격 입력받기
    price = int(input())

    # 10000원 이상이면 20% 할인
    if price >= 10000:
        price = int(price * 0.8)

    # 할인 적용된 가격 누적
    total += price

# 출력
print(f"총액: {total}원")

