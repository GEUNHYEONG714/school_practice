"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 9: 간단한 계산기

두 수와 연산자(+, -, *, /)를 입력받아 계산 결과를 출력합니다.

주의사항:
- 나누기(/)에서 두 번째 수가 0이면 "0으로 나눌 수 없습니다." 출력
- 지원하지 않는 연산자이면 "지원하지 않는 연산자입니다." 출력

힌트: 연산자를 if/elif로 판별하고, 나누기일 때 0 체크를 추가합니다.
"""

num1 = float(input("첫 번째 수를 입력하세요: "))
op = input("연산자를 입력하세요 (+, -, *, /): ")
num2 = float(input("두 번째 수를 입력하세요: "))

# 아래에 계산기를 구현하세요

# 연산자에 따른 계산
if op == "+":
    result = num1 + num2
    print(f"{num1} + {num2} = {result}")
    
elif op == "-":
    result = num1 - num2
    print(f"{num1} - {num2} = {result}")
    
elif op == "*":
    result = num1 * num2
    print(f"{num1} * {num2} = {result}")
    
elif op == "/":
    
    # 0으로 나누는 경우
    if num2 == 0:
        print(f"0으로 나눌 수 없습니다.")
    else:
        result = num1 / num2
        
        print(f"{num1} / {num2} = {result}")
else:
    # 잘못된 연산자인 경우
    print(f"지원하지 않는 연산자입니다.")



