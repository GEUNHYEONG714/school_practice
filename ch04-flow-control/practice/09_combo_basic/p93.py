"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 93: 비밀번호 생성기

비밀번호 길이 N을 입력받아, 알파벳 소문자와 숫자를 교대로 배치한
비밀번호를 생성하시오.

- 홀수 번째 자리(1,3,5,...): 알파벳 (a부터 순서대로)
- 짝수 번째 자리(2,4,6,...): 숫자 (1부터 순서대로)
- 알파벳이 z를 넘으면 다시 a부터, 숫자가 9를 넘으면 다시 0부터 반복

힌트: for문으로 한 글자씩 생성하며, chr()와 ord()를 활용합니다.
"""

n = int(input("비밀번호 길이: "))

# 아래에 코드를 작성하세요
password = ""

# 입력받은 길이만큼 반복
for i in range(n):

    # 홀수 번째 자리는 알파벳
    if i % 2 == 0:
        alpha = chr(ord("a") + (i // 2) % 26)
        password += alpha

    # 짝수 번째 자리는 숫자
    else:
        num = (i // 2 + 1) % 10
        password += str(num)

# 출력
print(password)

