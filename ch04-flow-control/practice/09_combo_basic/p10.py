"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 10: 가위바위보 확장

사용자가 가위(1), 바위(2), 보(3)를 입력하면
컴퓨터의 선택(숫자로 고정)과 비교하여 승/무/패를 판정합니다.

컴퓨터의 선택은 2(바위)로 고정합니다.
(참고: 나중에 random 모듈을 배우면 랜덤으로 바꿀 수 있습니다)

판정 규칙:
- 같으면: 무승부
- 가위 vs 보, 바위 vs 가위, 보 vs 바위: 승리
- 그 외: 패배

힌트: 사용자 선택과 컴퓨터 선택을 if/elif로 비교합니다.
"""

print("=== 가위바위보 게임 ===")
print("1: 가위, 2: 바위, 3: 보")
user = int(input("선택하세요 (1/2/3): "))

# 컴퓨터 선택 (고정값)
computer = 2

# 아래에 가위바위보 판정 코드를 작성하세요
if user < 1 or user > 3:
    print("잘못된 입력입니다. 1, 2, 3 중에서 선택하세요.")
else:
    # 숫자를 이름으로 변환하여 출력
    if user == 1:
        user_name = "가위"
    elif user == 2:
        user_name = "바위"
    else:
        user_name = "보"

    if computer == 1:
        com_name = "가위"
    elif computer == 2:
        com_name = "바위"
    else:
        com_name = "보"

    print("당신:", user_name, "/ 컴퓨터:", com_name)

    # 출력
    if user == computer:
        # 같은 경우 무승부
        print("무승부입니다! 😐")

    elif (user == 1 and computer == 3) or (user == 2 and computer == 1) or (user == 3 and computer == 2):
        # 이긴 경우
        print("축하합니다! 당신이 이겼습니다! 🎉")
    else:
        print("아쉽게도 졌습니다. 😢")

