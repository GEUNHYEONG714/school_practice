"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 16: N명 평균 점수

학생 수 N을 입력받고, N명의 점수를 입력받아 평균을 구하세요.

힌트: for문과 누적 변수를 사용합니다.
"""

# 아래에 코드를 작성하세요
num = int(input("학생 수를 입력하세요: "))

total = 0

# 학생 점수 입력
for i in range(1, num + 1):
    score = int(input(f"{i}번 학생 점수: "))
    total += score

# 평균 계산
average = total / num

# 출력
print(f"평균 점수: {average}")

