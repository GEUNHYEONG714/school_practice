"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 62: 영화관 좌석

영화관 좌석번호(1~100)를 입력받아 열과 번호 형식으로 변환합니다.

좌석 배치:
- 한 열에 10석씩, 총 10열(A~J)
- 좌석 1~10: A열 1~10번
- 좌석 11~20: B열 1~10번
- ...
- 좌석 91~100: J열 1~10번

범위 밖(1 미만 또는 100 초과)이면: 잘못된 좌석번호입니다.

힌트: 열은 (좌석번호-1) // 10으로 구하고, chr()로 알파벳 변환합니다.
"""

seat = int(input("좌석번호를 입력하세요: "))

# 아래에 코드를 작성하세요

# 좌석번호 범위 확인
if seat < 1 or seat > 100:
    print("잘못된 좌석번호입니다.")
else:
    # 열과 좌석 번호 계산
    row = (seat - 1) // 10
    num = (seat - 1) % 10 + 1

    # 숫자를 A~J 알파벳으로 변환
    row = chr(ord("A") + row)

    # 출력
    print(f"좌석 {seat} → {row}열 {num}번")

