"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 28: 완전수 판별

숫자를 입력받아 완전수인지 판별합니다.
완전수란 자기 자신을 제외한 약수의 합이 자기 자신과 같은 수입니다.
예: 6 = 1 + 2 + 3, 28 = 1 + 2 + 4 + 7 + 14

힌트: for + if를 사용합니다.
"""

num = int(input("숫자를 입력하세요: "))
total = 0

# 아래에 완전수를 판별하는 코드를 작성하세요
# 값 반복하며 확인
for i in range(1, num):
    if num % i == 0:
        # 누적 덧셈
        total += i

print(f"{num}의 약수의 합: total")

# num과 같으면 완전수
if total == num:
    print(f"{num}은(는) 완전수입니다!")
else:
    print(f"{num}은(는) 완전수가 아닙니다.")

