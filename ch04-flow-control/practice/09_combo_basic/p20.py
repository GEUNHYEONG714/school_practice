"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 20: 누적 합이 100 초과

숫자를 계속 입력받아 누적합을 구하다가,
누적합이 100을 넘으면 반복을 종료하고 결과를 출력하세요.

힌트: while문과 누적 변수, break를 사용합니다.
"""

# 아래에 코드를 작성하세요

# 변수 초기화
total = 0
count = 0

# 반복
while True:
    # 값 입력받기
    num = int(input("숫자를 입력하세요: "))
    
    # 누적 덧셈
    total += num
    
    # 반복할때마다 1씩 증가
    count += 1

    # 100 초과시 break
    if total > 100:
        break

print("누적합이 100을 초과했습니다!")
print("누적합:", total)
print("입력 횟수:", count)

