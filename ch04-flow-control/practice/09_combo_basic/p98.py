"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 98: 숫자 한글 변환기

1 이상 9999 이하의 정수를 입력받아 한글 읽기로 변환하여 출력하시오.

자릿수별 한글:
- 1~9: 일, 이, 삼, 사, 오, 육, 칠, 팔, 구
- 단위: 십(10), 백(100), 천(1000)

규칙:
- 천의 자리가 1이면 "일천"이 아닌 "천"으로 출력
- 백의 자리가 1이면 "일백"이 아닌 "백"으로 출력
- 십의 자리가 1이면 "일십"이 아닌 "십"으로 출력
- 0인 자릿수는 건너뜁니다.

힌트: 각 자릿수를 // 와 %로 분리하고, if문으로 1인 경우를 처리합니다.
"""

num = int(input("숫자(1~9999): "))

# 아래에 코드를 작성하세요
# 리스트 작성
number_list = ["", "일", "이", "삼", "사", "오", "육", "칠", "팔", "구"]
unit_list = ["", "십", "백", "천"]

# 초기화
result = ""

# 각 자릿수 확인
for i in range(3, -1, -1):

    # 현재 자릿수 숫자 구하기
    digit = num // (10 ** i) % 10
    
    # 숫자가 0이 아닌 경우
    if digit != 0:

        # 숫자가 1이면 일 생략
        if digit == 1 and i > 0:
            result += unit_list[i]
        else:
            result += number_list[digit] + unit_list[i]

# 결과 출력
print(result)
