"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 89: 숫자 야구 (간단)

2자리 정답이 37로 고정되어 있습니다.
사용자가 2자리 숫자를 입력하면 스트라이크/볼을 판정합니다.
정답을 맞출 때까지 반복합니다.

판정 규칙:
- 스트라이크: 같은 자리에 같은 숫자
- 볼: 다른 자리에 같은 숫자
- 둘 다 0이면: "아웃"

출력 형식:
- 맞출 때까지: "S스트라이크 B볼" 또는 "아웃"
- 맞추면: "정답! N번 만에 맞춤"

힌트: while True로 반복하며 십의 자리와 일의 자리를 각각 비교합니다.
"""

# 아래에 코드를 작성하세요
# 정답 37과 입력한 숫자의 각 자리 비교.
answer = "37"
count = 0

# 정답을 맞출 때까지 반복
while True:

    # 숫자 입력받기
    num = input()
    count += 1

    # 십의 자리와 일의 자리 분리
    first = num[0]
    second = num[1]

    # 스트라이크와 볼 초기화
    strike = 0
    ball = 0

    # 십의 자리 비교
    if first == answer[0]:
        strike += 1
    elif first == answer[1]:
        ball += 1

    # 일의 자리 비교
    if second == answer[1]:
        strike += 1
    elif second == answer[0]:
        ball += 1

    # 정답을 맞춘 경우
    if strike == 2:
        print(f"정답! {count}번 만에 맞춤")
        break

    # 스트라이크와 볼이 모두 0인 경우
    elif strike == 0 and ball == 0:
        print("아웃")

    # 스트라이크와 볼 출력
    else:
        print(f"{strike}스트라이크 {ball}볼")

