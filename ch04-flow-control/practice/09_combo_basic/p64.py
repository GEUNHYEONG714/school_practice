"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 64: 숫자 카운트

정수 N을 입력받아 1부터 N까지의 숫자 중에서:
- 3의 배수 개수
- 5의 배수 개수
- 3과 5 둘 다의 배수(15의 배수) 개수
를 각각 출력합니다.

힌트: for 반복문과 if로 각 배수를 카운트합니다.
"""

n = int(input("정수 N을 입력하세요: "))

# 아래에 코드를 작성하세요
count_3 = 0
count_5 = 0
count_15 = 0

# 1부터 N까지 반복
for num in range(1, n + 1):

    # 3의 배수 확인
    if num % 3 == 0:
        count_3 += 1

    # 5의 배수 확인
    if num % 5 == 0:
        count_5 += 1

    # 3과 5의 공배수 확인
    if num % 15 == 0:
        count_15 += 1

# 출력
print(f"3의 배수: {count_3}개")
print(f"5의 배수: {count_5}개")
print(f"3과 5의 공배수: {count_15}개")

