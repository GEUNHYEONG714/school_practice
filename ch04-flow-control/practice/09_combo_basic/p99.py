"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 99: 가위바위보 N판

가위바위보 게임을 N판 진행합니다.

- 첫째 줄: 판 수 N
- 다음 N줄: 플레이어의 선택 (가위, 바위, 보)
- 컴퓨터는 고정 패턴으로 "바위, 보, 가위"를 반복합니다.
  (1판: 바위, 2판: 보, 3판: 가위, 4판: 바위, ...)

각 판의 결과를 한 줄씩 출력합니다:
  `N판: 플레이어(X) vs 컴퓨터(Y) -> 결과`
  결과는 "승", "패", "무" 중 하나입니다.

마지막 줄에 `전적: A승 B패 C무`를 출력하시오.

힌트: 컴퓨터 패턴은 판 번호 % 3으로 결정합니다.
"""

n = int(input("판 수: "))

# 아래에 코드를 작성하세요
# 초기화
computer = ["바위", "보", "가위"]
win = 0
lose = 0
draw = 0

# 입력받은 판 수만큼 반복
for i in range(n):

    # 플레이어 선택 입력받기
    player = input()

    # 컴퓨터 선택 결정
    com = computer[i % 3]

    # 승패 판정
    if player == com:
        result = "무"
        draw += 1
    elif (player == "가위" and com == "보") or \
         (player == "바위" and com == "가위") or \
         (player == "보" and com == "바위"):
        result = "승"
        win += 1
    else:
        result = "패"
        lose += 1

    # 각 판 결과 출력
    print(f"{i + 1}판: 플레이어({player}) vs 컴퓨터({com}) -> {result}")

# 최종 전적 출력
print(f"전적: {win}승 {lose}패 {draw}무")

