"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 97: 성적 히스토그램

학생 수 N과 각 학생의 점수를 입력받아 10점 구간별 히스토그램을 출력하시오.

- 구간: 0~9, 10~19, 20~29, ..., 90~100
  (90~100 구간은 90점부터 100점까지 포함)
- 출력 형식: `구간: ###` (해당 구간 인원수만큼 # 출력)
- 인원이 0명인 구간은 출력하지 않습니다.

힌트: 구간별 개수를 변수로 관리하고, 점수 // 10으로 구간을 판별합니다.
      100점은 10구간이 아닌 9구간(90~100)에 포함시킵니다.
"""

n = int(input("학생 수: "))

# 아래에 코드를 작성하세요


# 구간별 인원수 초기화
scores = [0] * 10

# 학생 수만큼 점수 입력받기
for _ in range(n):
    score = int(input())

    # 점수에 따른 구간 계산
    index = score // 10

    # 100점은 마지막 구간에 저장
    if index == 10:
        index = 9

    # 구간별 인원수 증가
    scores[index] += 1

# 구간별 히스토그램 출력
for i in range(10):

    # 인원이 있는 구간만 출력
    if scores[i] > 0:

        # 구간 이름 설정
        if i == 9:
            section = "90~100"
        else:
            section = f"{i * 10}~{i * 10 + 9}"

        # 인원수만큼 # 출력
        print(f"{section}: {'#' * scores[i]}")
