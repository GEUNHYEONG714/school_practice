"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 63: 구구단 범위 출력

시작단과 끝단을 입력받아 해당 범위의 구구단을 출력합니다.

각 단은 --- N단 ---으로 시작하고,
N x M = 결과 형식으로 1~9까지 출력합니다.

힌트: 이중 for 반복문을 사용합니다.
"""

start = int(input("시작단을 입력하세요: "))
end = int(input("끝단을 입력하세요: "))

# 아래에 코드를 작성하세요
# 시작단부터 끝단까지 반복
for dan in range(start, end + 1):
    print(f"--- {dan}단 ---")

    # 1부터 9까지 반복
    for num in range(1, 10):
        # 구구단 계산
        result = dan * num

        # 출력
        print(f"{dan} x {num} = {result}")

