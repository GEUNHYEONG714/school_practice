"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 21: 배수 합계

두 자연수 N과 M을 입력받아,
1부터 N까지의 숫자 중 M의 배수만 모두 더한 합계를 구하세요.

힌트: for문과 if문, 누적 변수를 사용합니다.
"""

# 아래에 코드를 작성하세요
n = int(input("N을 입력하세요: "))
m = int(input("M을 입력하세요: "))

total = 0  # 배수 합계

# 1부터 N까지 반복
for i in range(1, n + 1):
    # M의 배수인지 확인
    if i % m == 0:
        total += i

print(f"1부터 {n}까지 {m}의 배수의 합: {total}")

