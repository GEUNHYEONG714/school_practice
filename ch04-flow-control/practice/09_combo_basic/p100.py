"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 100: 미니 은행

미니 은행 프로그램입니다. 초기 잔액과 3번의 거래를 처리합니다.

- 첫째 줄: 초기 잔액 (정수)
- 다음 3줄: 각 거래 (`입금 금액` 또는 `출금 금액` 또는 `조회`)

처리 규칙:
- 입금: 잔액에 금액을 더하고 `입금 완료: 잔액 X원` 출력
- 출금: 잔액이 충분하면 빼고 `출금 완료: 잔액 X원` 출력
         잔액이 부족하면 `출금 실패: 잔액 부족` 출력
- 조회: `현재 잔액: X원` 출력

마지막 줄에 `최종 잔액: X원`을 출력하시오.

힌트: 거래 문자열을 split()으로 분리하여 종류를 판별합니다.
"""

balance = int(input("초기 잔액: "))

# 아래에 코드를 작성하세요
# 3번 처리
for _ in range(3):
    # 거래 입력받기
    trade = input().split()

    # 거래 종류 확인
    if trade[0] == "입금":
        balance += int(trade[1])
        print(f"입금 완료: 잔액 {balance}원")

    elif trade[0] == "출금":
        money = int(trade[1])

        # 잔액이 충분한지 확인
        if balance >= money:
            balance -= money
            print(f"출금 완료: 잔액 {balance}원")
        else:
            print("출금 실패: 잔액 부족")

    elif trade[0] == "조회":
        print(f"현재 잔액: {balance}원")

# 최종 잔액 출력
print(f"최종 잔액: {balance}원")

