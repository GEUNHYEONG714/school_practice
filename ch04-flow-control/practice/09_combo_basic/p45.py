"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 45: 퀴즈 게임

5개의 산수 문제를 출제하고 정답을 확인한 뒤 최종 점수를 출력합니다.
- 문제는 두 수의 덧셈 (직접 값을 지정)
- 맞으면 "정답!", 틀리면 "오답! 정답은 ○○입니다"
- 최종 점수: 맞은 개수 × 20점

힌트: 변수에 문제와 정답을 직접 저장하고, if/else로 판별합니다.
"""

score = 0

# 문제 저장
problems = [
    (12, 8),
    (35, 17),
    (99, 1),
    (46, 27),
    (58, 34)
]
# 순서대로 꺼내기
for index, (a, b) in enumerate(problems, 1):
    answer = a + b

    print(f"문제 {index}: {a} + {b} = ?")
    # 답 입력받기
    user_answer = int(input("답: "))

    if user_answer == answer:
        print("정답!")
        score += 20
    else:
        print("오답! 정답은", str(answer) + "입니다")

print("점수:", score)


