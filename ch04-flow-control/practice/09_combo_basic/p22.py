"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 22: 자릿수 합 구하기

자연수를 입력받아 각 자릿수의 합을 구하세요.

[예시]
- 1234 → 1 + 2 + 3 + 4 = 10
- 567  → 5 + 6 + 7 = 18

힌트: while문과 %10(나머지), //10(몫)을 사용합니다.
"""
num = int(input("숫자를 입력하세요: "))
# 아래에 코드를 작성하세요
# 변수 초기화
total = 0

# 0보다 크면 반복
while num > 0:
    # 숫자 더함
    total += num % 10
    # 1씩 제거
    num = num // 10

print("각 자릿수의 합:", total)

