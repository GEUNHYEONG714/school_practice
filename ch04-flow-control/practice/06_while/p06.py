"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 6: 평균 구하기

숫자를 반복해서 입력받고, 0을 입력하면 입력을 멈춘 뒤
입력한 숫자들의 평균을 출력하세요. (0은 평균 계산에 포함하지 않습니다)

힌트: 합계와 개수를 각각 누적합니다.
"""

# 아래에 평균을 구하는 코드를 작성하세요
total = 0
count = 0
# 입력받기
num = int(input("숫자를 입력하세요 (0=종료): "))

# 0이 아닌 동안 반복
while num != 0:
    total += num  # total에 누적 덧셈
    count += 1    # count에 누적 증가
    # 입력받기
    num = int(input("숫자를 입력하세요 (0=종료): "))

# 평균 출력
if count > 0:
    print(f"평균: {total / count}")

