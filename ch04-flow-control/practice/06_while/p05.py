"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 5: 숫자 뒤집기

양의 정수를 입력받아 숫자를 뒤집어서 출력하세요.

힌트: %10으로 마지막 자리를 꺼내고,
      //10으로 마지막 자리를 제거합니다.
      뒤집은 숫자 = 뒤집은 숫자 * 10 + 마지막 자리
"""

num = int(input("양의 정수를 입력하세요: "))

# 아래에 숫자를 뒤집는 코드를 작성하세요
reverse_num = 0

while num > 0:
    last_num = num % 10     # 마지막 자리 숫자 꺼내기
    reverse_num = reverse_num * 10 + last_num  # 뒤집은 숫자에 추가
    num //= 10  # 마지막 자리 제거

print(f"뒤집은 숫자: {reverse_num}")

