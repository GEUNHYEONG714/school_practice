"""
실습 91 풀이: 지뢰 찾기 (간단)
"""
r0c0, r0c1, r0c2 = input().split()
r1c0, r1c1, r1c2 = input().split()
r2c0, r2c1, r2c2 = input().split()

# 정수 변환
r0c0 = int(r0c0)
r0c1 = int(r0c1)
r0c2 = int(r0c2)
r1c0 = int(r1c0)
r1c1 = int(r1c1)
r1c2 = int(r1c2)
r2c0 = int(r2c0)
r2c1 = int(r2c1)
r2c2 = int(r2c2)

# 각 칸의 출력값 계산
# (0,0): 주변 = (0,1), (1,0), (1,1)
if r0c0 == 1:
    o00 = "*"
else:
    o00 = str(r0c1 + r1c0 + r1c1)

# (0,1): 주변 = (0,0), (0,2), (1,0), (1,1), (1,2)
if r0c1 == 1:
    o01 = "*"
else:
    o01 = str(r0c0 + r0c2 + r1c0 + r1c1 + r1c2)

# (0,2): 주변 = (0,1), (1,1), (1,2)
if r0c2 == 1:
    o02 = "*"
else:
    o02 = str(r0c1 + r1c1 + r1c2)

# (1,0): 주변 = (0,0), (0,1), (1,1), (2,0), (2,1)
if r1c0 == 1:
    o10 = "*"
else:
    o10 = str(r0c0 + r0c1 + r1c1 + r2c0 + r2c1)

# (1,1): 주변 = (0,0), (0,1), (0,2), (1,0), (1,2), (2,0), (2,1), (2,2)
if r1c1 == 1:
    o11 = "*"
else:
    o11 = str(r0c0 + r0c1 + r0c2 + r1c0 + r1c2 + r2c0 + r2c1 + r2c2)

# (1,2): 주변 = (0,1), (0,2), (1,1), (2,1), (2,2)
if r1c2 == 1:
    o12 = "*"
else:
    o12 = str(r0c1 + r0c2 + r1c1 + r2c1 + r2c2)

# (2,0): 주변 = (1,0), (1,1), (2,1)
if r2c0 == 1:
    o20 = "*"
else:
    o20 = str(r1c0 + r1c1 + r2c1)

# (2,1): 주변 = (1,0), (1,1), (1,2), (2,0), (2,2)
if r2c1 == 1:
    o21 = "*"
else:
    o21 = str(r1c0 + r1c1 + r1c2 + r2c0 + r2c2)

# (2,2): 주변 = (1,1), (1,2), (2,1)
if r2c2 == 1:
    o22 = "*"
else:
    o22 = str(r1c1 + r1c2 + r2c1)

print(o00 + " " + o01 + " " + o02)
print(o10 + " " + o11 + " " + o12)
print(o20 + " " + o21 + " " + o22)
