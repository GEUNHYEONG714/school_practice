# 문제 3. 오류를 찾고 수정하기 어렵다
#
# 상황: 부가세(VAT)를 더한 최종 가격을 여러 곳에서 계산한다.
# 그런데 세율이 10% → 15%로 바뀌었다! 어디를 고쳐야 할까?
# 함수가 없으면 같은 계산 규칙이 여러 줄에 흩어진다.
# 흩어진 규칙은 빠뜨리거나 다르게 고치기 쉽다.

print("=" * 48)
print("[함수 없이] 같은 계산이 여러 곳에 흩어져 있다")
print("=" * 48)

# 가격마다 부가세 계산식을 복사해 두었다 (0.1 = 10%).
# 겉보기에는 단순하지만, 같은 숫자와 계산식이 여러 곳에 생긴다.
price_a = 10000
final_a = price_a + price_a * 0.1
print(f"상품A 최종가: {final_a:.0f}원")

price_b = 20000
final_b = price_b + price_b * 0.1
print(f"상품B 최종가: {final_b:.0f}원")

price_c = 30000
final_c = price_c + price_c * 0.15   # ← 실수! 여기만 0.15로 잘못 적었다
print(f"상품C 최종가: {final_c:.0f}원")

# 세율이 바뀌면 0.1을 '모든 곳에서' 찾아 고쳐야 한다.
# → 한 군데라도 빠뜨리거나 다르게 적으면(위 상품C처럼) 조용히 잘못된 값이 나온다.
# → 프로그램은 실행되므로, 이런 오류는 더 늦게 발견되기 쉽다.


print()
print("=" * 48)
print("[함수 사용] 규칙이 '한 곳'에만 있다")
print("=" * 48)

VAT_RATE = 0.1   # 세율은 여기 한 곳에서만 관리한다

def add_vat(price):
    # 부가세를 더하는 규칙도 이 함수 한 곳에만 둔다.
    return price + price * VAT_RATE

print(f"상품A 최종가: {add_vat(10000):.0f}원")
print(f"상품B 최종가: {add_vat(20000):.0f}원")
print(f"상품C 최종가: {add_vat(30000):.0f}원")

# 세율이 15%로 바뀌면? VAT_RATE 한 줄만 고치면 모든 계산이 한꺼번에 바뀐다.
#   - 빠뜨릴 곳이 없다  → 실수(버그)가 끼어들 틈이 없다.
#   - 고칠 곳이 한 곳뿐 → 수정이 쉽고 안전하다.
# 함수를 쓰면 "변경해야 할 지점"을 한 곳으로 모을 수 있다.
