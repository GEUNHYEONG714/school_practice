# 함수를 '언제' 만들어야 할까? — 5가지 신호
#
# 코드를 쓰다가 아래 신호가 보이면 "함수로 묶을 때"라는 힌트다.
# 함수는 아무 때나 많이 만드는 것이 아니라,
# 반복되는 규칙이나 의미 있는 작업 단위가 보일 때 만드는 것이 좋다.

# --------------------------------------------------------------
# 신호 1) 같은(또는 거의 같은) 코드가 2번 이상 나온다
#         → 복사-붙여넣기를 하려는 순간이 곧 함수로 만들 때다. (ex01 참고)
# --------------------------------------------------------------

# --------------------------------------------------------------
# 신호 2) 코드 묶음에 "# 이 부분은 ~하는 곳" 이라고 주석을 달고 싶다
#         → 그 주석이 바로 '함수 이름'이 된다.
#         → 이름이 생기면 코드를 읽는 사람이 의도를 더 빨리 파악한다.
# --------------------------------------------------------------

# [전] 주석으로 구역을 설명하는 코드
celsius = 25
# 섭씨를 화씨로 바꾸는 부분  ← 이런 주석을 달고 싶다면?
fahrenheit = celsius * 9 / 5 + 32
print(f"{celsius}°C = {fahrenheit}°F")

# [후] 그 주석을 '함수 이름'으로 승격시킨다
def celsius_to_fahrenheit(c):
    return c * 9 / 5 + 32

print(f"25°C = {celsius_to_fahrenheit(25)}°F")
print(f"30°C = {celsius_to_fahrenheit(30)}°F")
# 주석 대신 이름이 설명해 주고, 다시 쓰기도 쉬워진다.

# --------------------------------------------------------------
# 신호 3) "한 가지 일"로 이름 붙일 수 있는 의미 단위다
#         → 좋은 함수는 한 가지 일만 한다. (이름에 '그리고'가 들어가면 쪼개라)
#
# 신호 4) 나중에 또 쓸 것 같다 / 다른 곳에서도 쓰고 싶다
#         → 재사용할 기능은 함수로. (ex04 참고)
#
# 신호 5) 코드가 너무 길어 한눈에 안 들어온다
#         → 의미 단위로 잘라 이름을 붙이면 전체 흐름이 보인다. (ex02 참고)
#         → 함수 이름들이 목차처럼 보이면 읽기 쉬운 코드가 된다.
# --------------------------------------------------------------

print()
print("=" * 50)
print("정리: 함수가 필요하다는 신호")
print("=" * 50)
signals = [
    "같은 코드가 2번 이상 반복된다",
    "'이 부분은 ~하는 곳' 주석을 달고 싶다",
    "한 가지 일로 이름 붙일 수 있다",
    "나중에 또 / 다른 곳에서도 쓸 것 같다",
    "코드가 너무 길어 한눈에 안 들어온다",
]
for i, signal in enumerate(signals, 1):
    print(f"  {i}. {signal}")

print()
print("※ 단, 딱 한 번만 쓰는 아주 단순한 한 줄까지")
print("   억지로 함수로 만들 필요는 없다. (과하면 오히려 복잡해진다)")
