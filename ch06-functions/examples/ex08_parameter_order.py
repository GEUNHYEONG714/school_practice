# 매개변수를 정의하는 순서: 필수 → 기본값 → 가변 위치 → 가변 키워드
#
# 함수는 입력값, 즉 매개변수를 받는다. 그런데 입력값의 성격은 제각각이다.
#   - 반드시 받아야 하는 값이 있고 (예: 누구에게 보낼지)
#   - 생략하면 기본값을 쓰면 되는 값이 있고 (예: 우선순위 = "보통")
#   - 몇 개가 들어올지 모르는 값이 있고 (예: 받는 사람이 1명일 수도, 10명일 수도)
#   - 이름표를 붙여 자유롭게 받는 값도 있다. (예: 추가 옵션들)
#
# 파이썬은 이 네 가지를 한 함수에서 모두 쓸 수 있게 해준다.
# 단, 아래 순서대로 정의해야 한다. 순서를 어기면 SyntaxError가 발생한다.
#
#   def f(필수, 기본값=..., *가변위치, **가변키워드):
#         │      │            │           │
#         │      │            │           └ **kwargs : 이름표 달린 나머지 (dict)
#         │      │            └─────────── *args     : 나머지 위치 인자 (tuple)
#         │      └──────────────────────── 기본값 있는 매개변수
#         └─────────────────────────────── 필수 매개변수
#
# 이 파일의 목표:
#   1. 왜 "필수 → 기본값 → *args → **kwargs" 순서로 써야 하는지 이해한다.
#   2. 각 종류를 언제 쓰는지 예제로 확인한다.
#   3. 직접 함수를 설계할 때 매개변수 순서를 자신 있게 정한다.


