# 만약 기본값이 필수보다 앞에 오면 어떻게 될까?
#
#   def f(channel="SMS", message):   # ← SyntaxError! 파이썬이 정의 자체를 거부한다
#
# 이유: 호출 f("긴급!") 을 보자.
#   "긴급!" 이 channel 로 갈지 message 로 갈지 파이썬이 알 수 없다.
#   필수 매개변수(message)가 값을 못 받는 상황이 생길 수 있기 때문이다.
# 그래서 값을 꼭 채워야 하는 필수 매개변수는 앞에,
# 생략해도 되는 기본값 매개변수는 뒤에 둔다.
# 위치로 인자를 채워나갈 때 앞에서부터 빠짐없이 채워지도록 보장하는 규칙이다.
print("규칙: 필수가 앞 → 위치 인자가 앞에서부터 빈틈없이 채워진다")
