# 사용자 프로필을 만드는 함수. 이름은 필수지만, 추가 정보(나이/도시/취미 등)는
# 사람마다 다르고 종류도 미리 다 알 수 없다.
# 이런 값은 이름표(key=value)를 붙여 자유롭게 받으면 좋다.
#   - key=value 형태로 넘긴 인자들이 options라는 딕셔너리로 모인다.
def create_profile(name, **options):
    print(f"이름: {name}")
    for key, value in options.items():
        print(f"  - {key}: {value}")

create_profile("홍길동", age=20, city="서울")
create_profile("김철수", job="개발자", hobby="등산", blood_type="A")

# **kwargs가 맨 뒤에 오는 이유:
#   이름표 달린 나머지 인자를 모두 받는 자리이므로,
#   그 뒤에 다른 매개변수를 둘 수 없다.


