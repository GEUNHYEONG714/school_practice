# 영수증 합계를 내는 함수. 결제 항목이 1개일 수도, 5개일 수도 있다.
# 개수가 정해지지 않은 값들을 하나의 묶음으로 받고 싶을 때 *args를 쓴다.
#   - 호출할 때 넘긴 위치 인자들이 prices라는 튜플로 모인다.
def checkout(customer, *prices):
    total = sum(prices)
    print(f"{customer}님 / 항목 {len(prices)}개 / 합계 {total:,}원")

checkout("홍길동", 3000)                       # prices = (3000,)
checkout("김철수", 3000, 5000, 1500)           # prices = (3000, 5000, 1500)
checkout("이영희")                             # prices = () — 0개도 가능

# *args가 기본값 뒤에 오는 이유:
#   먼저 필수/기본값 매개변수의 자리를 채운 뒤,
#   남은 위치 인자들을 한꺼번에 모아야 하기 때문이다.
#   *args가 앞에 있으면, 그 뒤의 매개변수는 위치 인자로 값을 받기 어렵다.


