# 실무에서 흔한 로그 기록 함수를 네 종류의 매개변수로 설계해보자.
#   message          (필수)      : 무슨 일이 있었는지 — 없으면 로그의 의미가 없다
#   level="INFO"     (기본값)    : 중요도 — 대부분 INFO 라서 기본값으로
#   *tags            (가변 위치) : 분류용 태그 — 0개일 수도, 여러 개일 수도
#   **context        (가변 키워드): 부가 정보 — 상황마다 담을 내용이 다르다
def log(message, level="INFO", *tags, **context):
    tag_text = f" {list(tags)}" if tags else ""
    print(f"[{level}] {message}{tag_text}")
    for key, value in context.items():
        print(f"      {key}={value}")

# (1) 가장 간단한 호출: 필수 인자 하나만 전달
log("서버 시작됨")

# (2) 중요도만 바꿔서 전달
log("디스크 공간 부족", "WARNING")

# (3) 태그까지 전달: level 다음의 위치 인자들이 tags로 모인다
log("결제 실패", "ERROR", "payment", "card")

# (4) 부가 정보까지 전달: 이름표 달린 인자들은 context로 모인다
log("로그인", "INFO", "auth",
    user_id=1024, ip="192.168.0.10")

# 이 함수 하나가 간단한 기록부터 상세한 기록까지 모두 처리한다.
# → 매개변수의 다양성 덕분에 함수 하나로 여러 상황을 유연하게 감당할 수 있다.


