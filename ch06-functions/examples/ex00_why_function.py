# 왜 함수(Function)가 필요한가?
#
# 프로그램 = 알고리즘 + 데이터
#   - 알고리즘: 문제를 해결하기 위한 단계와 절차
#   - 데이터  : 그 절차가 다루는 값
#
# 그런데 프로그램 전체를 "하나의 긴 덩어리"로 작성하면
# 컴퓨터는 실행할 수 있어도, 사람이 읽고 고치기는 어려워진다.
#   1. 코드가 길어져 이해하기 어렵다.        → ex02_readability.py
#   2. 같은 코드를 반복해서 작성하게 된다.   → ex01_repetition.py
#   3. 오류를 찾고 수정하기 어렵다.          → ex03_maintenance.py
#   4. 기능을 재사용하기 어렵다.             → ex04_reuse.py
#
# 이 문제들을 해결하는 기본 도구가 바로 "함수"다.
# 함수 = 이름이 붙은 코드 묶음.
# 복잡한 절차를 함수 안에 넣고, 바깥에서는 그 이름으로 불러 쓴다.
# 입력을 받아 일을 하고, 필요하면 결과를 돌려준다.


# --- 사실 우리는 이미 함수를 쓰고 있다! ---
# print(), len(), sum(), input(), int() ... 이 모든 것이 "함수"다.
# 누군가 미리 만들어 둔 코드 묶음을, 우리는 그저 '이름'으로 불러서 쓴다.
# 그래서 매번 "화면에 출력하는 방법", "개수를 세는 방법"을 직접 쓰지 않아도 된다.

scores = [85, 92, 78]

print("점수 목록:", scores)        # print : 화면에 출력하는 함수
print("학생 수 :", len(scores))    # len   : 개수를 세는 함수
print("총점    :", sum(scores))    # sum   : 합을 구하는 함수

# 만약 sum()이 없다면? 합을 구하는 절차를 직접 써야 한다.
total = 0
for s in scores:
    total += s
print("sum 없이 직접 더하기:", total)   # → 같은 결과지만 '계산 절차'가 밖으로 드러난다


print()
print("=" * 50)
print("함수 덕분에 'sum(scores)' 한 줄이면 끝난다.")
print("이제 우리도 sum()처럼 '나만의 함수'를 만들어 볼 것이다.")
print("=" * 50)
print()


# --- 미리보기: 나만의 함수 만들기 ---
# def 함수이름(입력):
#     할 일
#     return 결과            (자세한 문법은 이번 챕터에서 차차 배운다)

def average(numbers):                     # 평균을 구할 값들을 입력으로 받아서
    return sum(numbers) / len(numbers)    # 평균 계산 절차를 함수 안에 숨긴다

print("내가 만든 average() 함수 사용:")
print("평균:", average(scores))
print("→ 한 번 만든 average()는 어디서든, 몇 번이든 다시 쓸 수 있다.")
