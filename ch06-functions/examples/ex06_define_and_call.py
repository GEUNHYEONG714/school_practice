# 함수의 정의(Definition)와 호출(Call) — 가장 기본
#
# 함수를 쓰려면 두 단계가 필요하다.
#   1. 정의(Definition): 함수를 '만들어 두는' 것       → def 로 작성한다
#   2. 호출(Call)      : 만들어 둔 함수를 '실행하는' 것 → 함수이름(...) 으로 부른다
#
# 비유하면, 정의는 '요리법을 적어 두는 것', 호출은 '그 요리법대로 요리하는 것'이다.
# 요리법만 적어 두었다고 음식이 만들어지지 않듯이,
# 함수도 정의만 해두면 아무 일도 일어나지 않는다.
# 호출해야 비로소 함수 본문이 실행된다.


# --- 함수 정의 : def + 이름 + 매개변수 + 콜론(:) ---
# 아래 코드는 "두 값을 더하는 방법"에 add 라는 이름을 붙여 둔 것이다.
def add(a, b):          # a, b : 매개변수(Parameter) — 입력을 받는 변수
    result = a + b      # 본문(Body)은 들여쓰기로 블록을 구분한다
    return result       # return : 계산 결과를 호출한 곳으로 돌려준다


# --- 함수 호출(Call) ---
# 함수 이름 뒤에 괄호를 붙여야 함수가 실행된다.
print(add(3, 5))        # 3, 5 : 인자(Argument) → 결과 8

# 호출할 때마다 함수 본문이 다시 실행된다.
# 같은 규칙(add)을 쓰되, 인자만 바꾸면 다른 결과를 얻을 수 있다.
print(add(10, 20))      # → 30
print(add(-2, 7))       # → 5

# 반환값(return)은 변수에 담아 다시 활용할 수 있다.
# 그래서 함수는 "계산하고 끝"이 아니라, 다음 코드에 결과를 넘겨줄 수 있다.
total = add(100, 200)
print("합계:", total)


