# - 매개변수(Parameter): 정의할 때 괄호 안에 적는 '받을 변수'  → def add(a, b)
# - 인자(Argument)     : 호출할 때 실제로 넣어 주는 '값'        → add(3, 5)
# 즉, 인자 3, 5 가 매개변수 a, b 로 전달되어 본문이 실행된다.
# 매개변수는 함수 안에서만 쓰는 임시 이름이라고 생각하면 쉽다.
print("add(3, 5) → a=3, b=5 로 전달 → 반환값", add(3, 5))


