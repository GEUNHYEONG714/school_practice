def say_hello():
    print(">> say_hello() 의 본문이 실행됨!")

# 위에서 say_hello()를 정의했지만, 아직 출력은 일어나지 않았다.
# 프로그램은 위에서 아래로 실행되다가 함수 호출을 만났을 때 함수 안으로 들어간다.
print("1. 함수를 정의했지만, 아직 본문은 실행되지 않았다.")
