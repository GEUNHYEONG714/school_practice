# 입력이 필요 없으면 매개변수 자리를 비워 둔다.
# 그래도 호출할 때는 ()를 꼭 붙인다. 괄호가 "함수를 실행하라"는 표시다.
def print_line():
    print("-" * 20)

print_line()
