# return 이 있는 함수: 결과를 '돌려준다' → 그 값을 다시 활용할 수 있다
# 예: 계산 함수는 보통 return으로 결과를 돌려준다.
def square(x):
    return x * x

# return 이 없는 함수: 일(출력 등)만 하고, 돌려주는 값은 없다
# 예: 화면에 보여 주는 함수는 출력 자체가 목적일 수 있다.
def greet(name):
    print(f"안녕하세요, {name}님!")

result = square(4)
print("square(4)의 반환값:", result)    # 16

greet("홍길동")                          # 인사만 출력한다
value = greet("김철수")                  # return 이 없으면 반환값은 None 이다
print("greet()의 반환값:", value)        # None


