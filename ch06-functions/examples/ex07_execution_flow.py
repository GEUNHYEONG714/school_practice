# 함수 호출과 실행 흐름 — "반드시 호출 지점으로 되돌아온다"
#
# 프로그램은 기본적으로 위에서 아래로 한 줄씩 실행된다.
# 하지만 함수를 호출하는 순간, 실행 흐름(디버거의 노란 화살표)은
# 잠시 함수 본문으로 '이동'했다가 일을 마친 뒤 다시 돌아온다.
#
# 중요한 점:
# 함수는 아무 곳으로 돌아오는 것이 아니라,
# 반드시 자신을 호출한 '그 자리'로 돌아온다.
#
#   호출하는 쪽(main)  --- 1. 호출 / 인자값 전달 --->  함수 정의(Definition)
#   호출하는 쪽(main)  <-- 2. return / 반환값과 함께 복귀 --
#
# 이 파일은 그 흐름을 두 가지 방법으로 확인하기 위한 예제다.
#   1. print 출력으로 흐름을 눈으로 따라가기
#   2. VS Code 디버거로 노란 화살표가 이동하는 모습 직접 보기


# ══════════════════════════════════════════════════════════════
# VS Code 디버거로 실행 흐름 직접 보기  (아래 순서대로 따라 해보자)
# ══════════════════════════════════════════════════════════════
#
# [1] 중단점(Breakpoint) 찍기
#     - 줄 번호 왼쪽을 클릭하면 빨간 점이 생긴다 → 그 줄에서 실행이 멈춘다.
#     - 아래 'result = add(3, 5)' 줄에 하나 찍어 보자.
#     - 중단점은 "여기서 잠깐 멈춰서 상태를 보겠다"는 표시다.
#
# [2] 디버깅 시작
#     - F5 → 'Python Debugger: Python File' 선택
#     - 노란 화살표(현재 실행 위치)가 중단점에서 멈춘다.
#
# [3] 한 줄씩 실행하는 단축키
#     - F11 (Step Into)     : 함수 호출이면 그 함수 '안으로' 들어간다   ← 흐름 이동을 본다
#     - Shift+F11 (Step Out): 현재 함수를 끝내고 '호출한 곳으로' 나온다 ← 복귀를 본다
#     - F10 (Step Over)     : 현재 줄 실행. 함수 호출이면 안 들어가고 통째로 실행
#     - F5  (Continue)      : 다음 중단점까지 쭉 실행
#
# [4] 꼭 관찰할 것
#     - add 호출 줄에서 F11 → 노란 화살표가 'def add' 본문으로 이동한다.  (그림 1번)
#     - 왼쪽 '호출 스택(CALL STACK)' 패널: 함수에 들어가면 쌓이고, return 하면 줄어든다.
#     - return 을 지나면 노란 화살표가 '호출했던 줄'로 되돌아온다.       (그림 2번)
#     - '변수(VARIABLES)' 패널에서 a, b, result 값이 변하는 것도 볼 수 있다.
#     - 즉, 디버거는 함수가 "어디로 들어가고 어디로 돌아오는지"를 보여 주는 도구다.
# ══════════════════════════════════════════════════════════════


def add(a, b):
    # add()가 호출되면 실행 흐름은 잠시 이 함수 안으로 들어온다.
    # return 값을 만나면 계산 결과를 가지고 호출한 줄로 돌아간다.
    return a + b


print("=" * 50)
print("기본 흐름 (슬라이드 그림과 동일)")
print("=" * 50)

# 이 줄에 중단점을 찍고 F11 로 add 안으로 들어가 보자.
# 노란 화살표가 아래 줄에서 add() 함수 안으로 이동하는지 확인한다.
result = add(3, 5)   # 1. 호출 / 인자값 전달 → 흐름이 add 본문으로 이동
print(result)        # 3. 반환된 8이 result에 저장된 뒤, 이 줄이 실행된다


# ──────────────────────────────────────────────────────────────
# 핵심 1) 같은 함수라도, '호출한 그 자리'로 정확히 돌아온다
# ──────────────────────────────────────────────────────────────
# 함수는 "내가 어디서 불렸는지"를 기억한다.
# 정해진 한 곳으로 돌아가는 것이 아니라, 호출한 바로 그 지점으로 돌아온다.
# 아래에서는 같은 double()을 A 지점과 B 지점, 두 곳에서 불러 이 차이를 확인한다.

def double(n):
    # 이 출력들은 double() 안에 들어왔는지, 언제 나가는지 확인하기 위한 표시다.
    print(f"   [double 안] 들어옴: n={n}")
    answer = n * 2
    print(f"   [double 안] 나감: {n} → {answer} 반환")
    return answer


print()
print("=" * 50)
print("핵심 1) 호출 지점마다 그 자리로 복귀")
print("=" * 50)

print("A 지점: double(10) 호출")
x = double(10)                       # ← double이 끝나면
print(f"A 지점으로 복귀 → x={x}")    #    바로 이 줄로 돌아온다

print("B 지점: double(7) 호출")
y = double(7)                        # ← 같은 double인데 이번엔
print(f"B 지점으로 복귀 → y={y}")    #    이 줄로 돌아온다 (A가 아니다!)

# 반복문 안에서 호출해도 마찬가지다.
# 매번 double() 안으로 들어갔다가, 다시 반복문 안의 호출 지점으로 돌아와 다음 줄을 실행한다.
print("반복문 안에서 호출:")
for i in [1, 2, 3]:
    r = double(i)
    print(f"   반복 {i}: 돌아와서 계속 진행 → {r}")


# ──────────────────────────────────────────────────────────────
# 핵심 2) 중첩 호출 — 호출 스택(Call Stack)이 쌓였다가 풀린다
# ──────────────────────────────────────────────────────────────
# 함수가 또 다른 함수를 부르면, 복귀할 자리가 차곡차곡 쌓인다.
# 이 복귀할 자리들의 목록을 호출 스택(Call Stack)이라고 생각하면 된다.
# 디버거의 '호출 스택' 패널에서 이 모습을 가장 잘 볼 수 있다.
#   들어갈 때:  main → step1 → step2 → step3  (쌓임)
#   나올 때 :  step3 → step2 → step1 → main  (역순으로 복귀)

def step3():
    print("         step3 시작")
    print("         step3 끝 → step2로 복귀")

def step2():
    print("      step2 시작")
    step3()                              # step3 호출: 흐름이 step3 안으로 이동
    print("      step2 끝 → step1로 복귀")   # step3가 끝나면 여기로 돌아온다

def step1():
    print("   step1 시작")
    step2()                              # step2 호출: 흐름이 step2 안으로 이동
    print("   step1 끝 → main으로 복귀")     # step2가 끝나면 여기로 돌아온다


print()
print("=" * 50)
print("핵심 2) 중첩 호출과 복귀 (호출 스택)")
print("=" * 50)
# 팁: step1() 줄에 중단점을 찍고 F11을 계속 눌러 보자.
#     호출 스택이 step1 ▸ step2 ▸ step3 로 쌓였다가, 하나씩 사라지며 복귀한다.
#     마지막에는 step1()을 호출했던 main 영역의 다음 줄로 돌아온다.
step1()
print("main으로 완전히 복귀 — 프로그램 끝")
